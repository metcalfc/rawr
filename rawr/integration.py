"""Additive Rex actions and explicitly installed project-tool key bindings."""
from __future__ import annotations

from contextlib import contextmanager
import fcntl
import os
from pathlib import Path
import re
import shutil
import stat
import sys
import tempfile
from typing import Callable, Mapping, Sequence


class IntegrationError(RuntimeError):
    """An integration update could not be made without overwriting user config."""


BEGIN = b"\n-- BEGIN RAWR PROJECTS (managed)\n"
END = b"-- END RAWR PROJECTS (managed)\n"
TOGGLE_TOOLS = (("files", "Files"), ("github", "GitHub"), ("exedev", "exe.dev"))
DEFAULT_BINDINGS = {"files": "cmd+alt+1", "github": "cmd+alt+2", "exedev": "cmd+alt+3"}
ACTION_NAMES = ("rawr_projects", "rawr_activity", *("rawr_toggle_" + role for role, _ in TOGGLE_TOOLS))


def default_config_path() -> Path:
    if os.environ.get("REX_CONFIG"):
        return Path(os.environ["REX_CONFIG"]).expanduser()
    return Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))) / "rex" / "init.lua"


def lua_quote(value: str) -> str:
    """A Lua 5.1 string literal, retaining Unicode and escaping every control."""
    if not isinstance(value, str) or "\0" in value:
        raise IntegrationError("launcher arguments must be strings without NUL")
    result = '"'
    for char in value:
        code = ord(char)
        if char in ('"', "\\"):
            result += "\\" + char
        elif code < 32 or code == 127:
            result += "\\" + format(code, "03d")
        else:
            result += char
    return result + '"'


def _bindings(bindings: Mapping[str, str] | None) -> dict[str, str]:
    selected = dict(DEFAULT_BINDINGS if bindings is None else bindings)
    if any(role not in DEFAULT_BINDINGS or not isinstance(key, str) or not key.strip() or "\0" in key
           for role, key in selected.items()):
        raise IntegrationError("bindings must map files/github/exedev to nonempty Rex key strings")
    normalized = [_canonical_chord(key) for key in selected.values()]
    if len(normalized) != len(set(normalized)):
        raise IntegrationError("tool toggle bindings must use distinct keys")
    return selected


def _canonical_chord(key: str) -> tuple[str, ...]:
    """Compare literal key chords without depending on modifier order/spelling.

    Sequences sharing a first chord also conflict with a single-chord toggle.
    Mode-prefixed bindings are separate and are intentionally not conflated.
    """
    first = key.strip().lower().split(">", 1)[0].strip()
    aliases = {"command": "cmd", "super": "cmd", "option": "alt", "opt": "alt",
               "control": "ctrl"}
    return tuple(sorted(aliases.get(part.strip(), part.strip()) for part in first.split("+")))


def render_actions(launcher: Sequence[str] | None = None,
                   bindings: Mapping[str, str] | None = None) -> str:
    """Return actions suitable for init.lua or an explicit `rex do` script.

    launcher is an argv prefix, not a shell command. Rex hosts the picker in a
    fresh native terminal and no input is sent to an existing terminal.
    """
    if launcher is None:
        launcher = [sys.executable, str(Path(__file__).resolve().parents[1] / "bin" / "rawr")]
    if not launcher:
        raise IntegrationError("launcher argv cannot be empty")
    selected_bindings = _bindings(bindings)
    command = ", ".join(lua_quote(arg) for arg in [*launcher, "pick"])
    directories = set()
    for name in ("gh", "git", "ssh", "open"):
        found = shutil.which(name)
        if found:
            directories.add(str(Path(found).parent))
    dependency_paths = ", ".join(lua_quote(directory) for directory in sorted(directories))
    generated = '''-- Generated by rawr; independent native terminals, no layout repair loop.
rex.action {
  name = "rawr_projects",
  title = "Projects: Open Project…",
  category = "Projects",
  keywords = "rawr project workspace picker native",
  run = function(ctx, args)
    if not ctx.session_id then
      error("Open Projects from an existing Rex session, or use rawr pick in a terminal")
    end
    local created, err = rex.session.new_window {
      session_id = ctx.session_id,
      window_label = "Projects",
      focus = true,
      layout = { block = {
        flavor = "com.superlogical.terminal.shell",
        label = "Project picker",
        options = { shell = "none", login = false, path_prepend = { ''' + dependency_paths + ''' }, command = { ''' + command + ''' } }
      } }
    }
    if not created then error(err) end
    return created
  end
}

rex.action {
  name = "rawr_activity",
  title = "Projects: Native Activity",
  category = "Projects",
  keywords = "rawr project agent activity status",
  run = function(ctx, args)
    rex.client.queue("client.sidebar.activity.by_session", {})
  end
}
'''
    for role, title in TOGGLE_TOOLS:
        toggle_command = ", ".join(lua_quote(arg) for arg in [*launcher, "toggle-session", role, "--session"])
        generated += '''
rex.action {
  name = "rawr_toggle_''' + role + '''",
  title = "Projects: Toggle ''' + title + '''",
  category = "Projects",
  keywords = "rawr project tool toggle open close hide show ''' + role + '''",
  run = function(ctx, args)
    if not ctx.session_id then
      error("Toggle tools from an associated project session")
    end
    local result, err = rex.exec({ ''' + toggle_command + ''', ctx.session_id }, { timeout = 30 })
    if not result then error(err) end
    if not result.ok then
      local detail = result.stderr
      if not detail or detail == "" then detail = result.stdout end
      error("Rawr toggle failed: " .. (detail or "command did not complete"))
    end
    local decoded, decode_err = rex.json.decode(result.stdout)
    if type(decoded) ~= "table" or decoded.result ~= "complete" then
      error("Rawr toggle returned an incomplete result: " .. (decode_err or result.stdout))
    end
    return decoded
  end
}
'''
    for role, key in selected_bindings.items():
        generated += '\nrex.bind(' + lua_quote(key) + ', ' + lua_quote("rawr_toggle_" + role) + ')\n'
    return generated


def _split_owned(content: bytes) -> tuple[bytes, bytes, bytes]:
    """Return prefix/owned/suffix; malformed or duplicate ownership is a conflict."""
    begins = content.count(b"-- BEGIN RAWR PROJECTS")
    ends = content.count(b"-- END RAWR PROJECTS")
    if begins == ends == 0:
        return content, b"", b""
    if begins != 1 or ends != 1 or BEGIN not in content or END not in content:
        raise IntegrationError("malformed or duplicate rawr managed markers; repair the Rex config before updating")
    begin = content.index(BEGIN)
    end = content.index(END) + len(END)
    if end <= begin:
        raise IntegrationError("rawr managed markers are out of order; Rex config was left unchanged")
    return content[:begin], content[begin:end], content[end:]


@contextmanager
def _config_lock(config: Path):
    config.parent.mkdir(parents=True, exist_ok=True)
    lock = config.with_name(config.name + ".rawr.lock")
    with lock.open("a+b") as handle:
        os.chmod(lock, 0o600)
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
        yield


def _read(config: Path) -> bytes:
    if config.is_symlink():
        raise IntegrationError("Rex config is a symlink; pass its resolved target explicitly")
    try:
        return config.read_bytes()
    except FileNotFoundError:
        return b""


def _replace(config: Path, old: bytes, new: bytes, validate: Callable[[Path], None] | None):
    mode = stat.S_IMODE(config.stat().st_mode) if config.exists() else 0o600
    fd, temporary = tempfile.mkstemp(prefix="." + config.name + ".rawr-", dir=config.parent)
    temporary_path = Path(temporary)
    try:
        with os.fdopen(fd, "wb") as handle:
            os.fchmod(handle.fileno(), mode)
            handle.write(new)
            handle.flush()
            os.fsync(handle.fileno())
        if validate:
            validate(temporary_path)
        if _read(config) != old:
            raise IntegrationError("Rex config changed during update; retry after reviewing the concurrent edit")
        os.replace(temporary_path, config)
        directory = os.open(config.parent, os.O_RDONLY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        temporary_path.unlink(missing_ok=True)


def install(config_path: str | Path | None = None, launcher: Sequence[str] | None = None,
            validate: Callable[[Path], None] | None = None,
            bindings: Mapping[str, str] | None = None) -> dict:
    """Install/update only our marked actions; caller may validate the temp Lua.

    This does not reload Rex. A validation callback must raise on invalid Lua,
    and receives a temporary path with the entire proposed configuration.
    """
    config = Path(config_path) if config_path is not None else default_config_path()
    selected_bindings = _bindings(bindings)
    generated = render_actions(launcher, selected_bindings).encode("utf-8")
    with _config_lock(config):
        old = _read(config)
        prefix, owned, suffix = _split_owned(old)
        unrelated = prefix + suffix
        for action in ACTION_NAMES:
            if re.search(rb"\bname\s*=\s*['\"]" + action.encode() + rb"['\"]", unrelated):
                raise IntegrationError("Rex config already defines " + action + " outside rawr's block; choose/remove that conflicting action first")
        # Runtime/default bindings are checked separately through Rex's effective
        # keymap before installation. Refuse literal conflicts in init.lua here.
        targets = {_canonical_chord(key) for key in selected_bindings.values()}
        for match in re.finditer(rb"\brex\s*\.\s*bind\s*\(\s*(['\"])([^'\"\r\n]*)\1", unrelated):
            key = match.group(2).decode("utf-8", errors="replace")
            if _canonical_chord(key) in targets:
                raise IntegrationError("Rex config already binds " + key + " outside rawr's block; choose a different toggle shortcut")
        new = prefix + BEGIN + generated + END + suffix
        changed = new != old
        if changed:
            _replace(config, old, new, validate)
        return {"changed": changed, "path": str(config), "actions": list(ACTION_NAMES), "bindings": selected_bindings}


def uninstall(config_path: str | Path | None = None,
              validate: Callable[[Path], None] | None = None) -> dict:
    """Remove only the managed block, retaining all surrounding bytes."""
    config = Path(config_path) if config_path is not None else default_config_path()
    if not config.parent.exists():
        return {"changed": False, "path": str(config), "actions": []}
    with _config_lock(config):
        old = _read(config)
        prefix, owned, suffix = _split_owned(old)
        if owned:
            _replace(config, old, prefix + suffix, validate)
        return {"changed": bool(owned), "path": str(config), "actions": []}
